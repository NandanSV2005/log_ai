"""
LOG AI — API Keys Management Endpoints
======================================
Authenticated REST endpoints for users to provision, inspect, and revoke
high-entropy ingestion API keys.
"""

import logging
from typing import List, Optional, Dict, Any
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field

from app.routers.auth import get_current_user
from app.services.api_key_service import (
    create_api_key,
    list_api_keys,
    revoke_api_key,
)

logger = logging.getLogger("log_ai.api_keys.router")
router = APIRouter(prefix="/api/v1/api-keys", tags=["API Keys"])


def _get_username(user: Optional[object]) -> str:
    if not user:
        return "default_user"
    if hasattr(user, "username") and getattr(user, "username"):
        return str(getattr(user, "username"))
    if isinstance(user, dict):
        u = user.get("username") or user.get("sub")
        if u:
            return str(u)
    if isinstance(user, str) and not user.startswith("<"):
        return user
    return "default_user"


class ApiKeyCreateRequest(BaseModel):
    name: Optional[str] = Field("Forwarder Agent", description="Friendly label for this API key")


class ApiKeyCreatedResponse(BaseModel):
    id: int
    name: str
    display_prefix: str
    api_key: str = Field(..., description="Plaintext secret token. SHOWN ONCE AT CREATION.")
    raw_key: Optional[str] = Field(None, description="Plaintext token alias")
    key: Optional[Dict[str, Any]] = Field(None, description="Key metadata dict")
    created_at: str
    last_used_at: Optional[str] = None
    revoked: bool
    status: str


class ApiKeyInfoResponse(BaseModel):
    id: int
    name: str
    display_prefix: str
    owner_username: str
    created_at: str
    last_used_at: Optional[str] = None
    revoked: bool
    status: str


@router.post("", response_model=ApiKeyCreatedResponse, status_code=status.HTTP_201_CREATED)
async def generate_key(
    payload: ApiKeyCreateRequest,
    current_user=Depends(get_current_user),
):
    """
    Generates a new ingestion API key bound to the authenticated user.
    The plaintext secret is returned ONCE in this response and is never stored or displayed again.
    """
    username = _get_username(current_user)
    name = (payload.name or "").strip() or "Forwarder Agent"

    key_data, plaintext_token = create_api_key(owner_username=username, name=name)

    logger.info("Generated new Ingest API Key #%s for user '%s'", key_data["id"], username)

    return ApiKeyCreatedResponse(
        id=key_data["id"],
        name=key_data["name"],
        display_prefix=key_data["display_prefix"],
        api_key=plaintext_token,
        raw_key=plaintext_token,
        key=key_data,
        created_at=key_data["created_at"],
        last_used_at=key_data["last_used_at"],
        revoked=key_data["revoked"],
        status=key_data["status"],
    )


@router.get("", response_model=List[ApiKeyInfoResponse])
async def list_keys(
    current_user=Depends(get_current_user),
):
    """
    Lists all API keys generated by the authenticated user.
    Plaintext secrets and cryptographic hashes are never exposed.
    """
    username = _get_username(current_user)
    keys = list_api_keys(owner_username=username)
    return keys


@router.delete("/{key_id}", status_code=status.HTTP_200_OK)
async def revoke_key(
    key_id: int,
    current_user=Depends(get_current_user),
):
    """
    Revokes an API key owned by the authenticated user.
    Subsequent agent ingestion attempts using this key will be rejected with HTTP 401.
    """
    username = _get_username(current_user)
    success = revoke_api_key(key_id=key_id, owner_username=username)
    if not success:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"API key #{key_id} not found or not owned by user",
        )

    logger.info("Revoked Ingest API Key #%s for user '%s'", key_id, username)
    return {"status": "success", "message": f"API key #{key_id} has been revoked."}
